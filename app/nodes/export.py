"""`export` node: turn a passed gate into one immutable standard file.

Spec: `orchestration` -> *导出标准文件*. Design: `poc-skeleton/design.md` §9.

Two independent guards stop a blocked run from exporting:

1. the router does not send `gate=blocked` here at all;
2. the node itself refuses unless `gate.verdict == "pass"` (defence against a future routing bug).

The version number is generated by `DocVersionStore`, never accepted from the caller.
"""

from __future__ import annotations

from datetime import datetime, timezone

from app.audit.snapshot import snapshot_digest
from app.stages import stage_report
from app.storage.doc_versions import DocVersionStore

EXPORT_STAGE = "export"


def export_node(state: dict, *, versions: DocVersionStore | None = None) -> dict:
    """Write the standard file when the gate passed; always return an `export` stage report."""
    gate = state.get("gate") or {}
    if gate.get("verdict") != "pass":
        return {
            "export": None,
            "stages": [
                stage_report(
                    EXPORT_STAGE,
                    status="skipped",
                    reason="gate did not pass: "
                    + (", ".join(gate.get("reason_codes") or []) or "no decision"),
                )
            ],
        }

    store = versions or DocVersionStore()
    run_id = str(state.get("run_id") or "run")
    snapshot_id = str(gate.get("candidate_content_sha256") or snapshot_digest(state))
    payload = {
        "doc_id": run_id,
        "snapshot_id": snapshot_id,
        "run_id": run_id,
        "business_type": state.get("business_type"),
        "fields": state.get("fields") or {},
        "extra_fields": state.get("extra_fields") or {},
        "verification": state.get("verification"),
        "gate": gate,
        "exported_at": datetime.now(timezone.utc).isoformat(),
    }
    version = store.append(run_id, payload)
    return {
        "export": {**payload, **version},
        "stages": [
            stage_report(
                EXPORT_STAGE,
                status="done",
                produced=len(payload["fields"]) + len(payload["extra_fields"]),
                model_calls=0,
            )
        ],
    }


__all__ = ["EXPORT_STAGE", "export_node"]
